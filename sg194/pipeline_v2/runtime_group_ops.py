def generate_outputs() -> dict[str, Any]:
    ctx = bridge.load_context()
    census = build_local_rep_census(ctx)
    expanded = build_expanded_candidates(ctx)
    basis = choose_integer_basis(expanded)
    bs_vs_ai = build_bs_vs_ai_expanded_summary(expanded, basis, ctx)

    write_text(LOCAL_REP_CENSUS_AUDIT_MD, build_local_rep_census_md(census, ctx))
    write_json(LOCAL_REP_CENSUS_SUMMARY_JSON, census)
    write_json(AI_EXPANDED_CANDIDATES_JSON, build_candidates_json(expanded, ctx))
    write_json(AI_EXPANDED_MATRIX_JSON, build_matrix_json(expanded, basis, ctx))
