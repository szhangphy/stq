def induce_candidate(
    entry: dict[str, Any],
    local_rep: dict[str, Any],
    ctx: dict[str, Any],
    group_tables: dict[str, Any],
    manifold_globals: dict[str, list[int]],
) -> dict[str, Any]:
    orbit = orbit_for_sample_entry(entry, ctx, group_tables)
    stabilizer = bridge.bridge_stabilizer_for_entry(entry, ctx)
    stabilizer_unitary = set(stabilizer["unitary_indices"])
    local_character = {int(index): int(value) for index, value in local_rep["character_on_unitary_stabilizer"].items()}

    manifold_multiplicities: dict[str, list[int]] = {}
    manifold_band_characters: dict[str, list[dict[str, float]]] = {}

    for manifold in MANIFOLDS:
        info = bridge.manifold_linear_characters(manifold, ctx)
        band_character: list[complex] = []
        for op_index, rotation, translation in zip(
            manifold_globals[manifold],
            info["unitary_rotations"],
            info["unitary_translations"],
        ):
            total = 0j
            for site in orbit:
                coset_index = int(site["source_operation_index"])
                conj_index = group_tables["compose"](
                    group_tables["inverse"][coset_index],
                    group_tables["compose"](op_index, coset_index),
                )
                if conj_index not in stabilizer_unitary:
                    continue
                point_conv = np.array(site["conv_vector"], dtype=float)
                delta = rotation @ point_conv + translation - point_conv
                fixed, _ = bridge.vector_is_lattice(ctx["supercell"], delta)
                if not fixed:
                    continue
                total += local_character[conj_index] * cmath.exp(-1j * float(np.dot(info["kconv"], delta)))
            band_character.append(total)

        chars = info["linear_characters"]
        band = np.array(band_character, dtype=complex)
        gram = chars @ chars.conj().T / chars.shape[1]
        rhs = chars.conj() @ band / chars.shape[1]
        multiplicities = np.linalg.solve(gram, rhs)
        if not np.allclose(multiplicities, np.rint(multiplicities.real), atol=1e-8):
            raise ValueError(f"{local_rep['id']} on {manifold}: multiplicities are not integral")

        multiplicities_round = [int(round(float(value.real))) for value in multiplicities]
        recon = np.array(multiplicities_round, dtype=complex) @ chars
        if not np.allclose(recon, band, atol=1e-8):
            raise ValueError(f"{local_rep['id']} on {manifold}: character reconstruction failed")

        manifold_multiplicities[manifold] = multiplicities_round
        manifold_band_characters[manifold] = [
            {"real": round(value.real, 12), "imag": round(value.imag, 12)} for value in band_character
        ]

    unknown_vector: list[int] = []
    for token in ctx["basis_raw"]["unknown_ordering"]:
        manifold, rep_index_str = token.split("_R")
        unknown_vector.append(manifold_multiplicities[manifold][int(rep_index_str) - 1])

    compatibility = sp.Matrix(ctx["compat"]["global_matrix"]) * sp.Matrix(unknown_vector)
    compatibility_zero = all(int(value) == 0 for value in list(compatibility))

    basis_matrix = sp.Matrix.hstack(*[sp.Matrix(column["vector"]) for column in ctx["basis_raw"]["basis_vectors"]])
    coeff_solution = basis_matrix.gauss_jordan_solve(sp.Matrix(unknown_vector))[0]
    coeffs = [int(value) for value in coeff_solution]

    sample_mag = bridge.representative_sample_point_magnetic(entry)
    sample_conv = sample_point_conventional(entry, ctx)

    return {
        "generator_id": local_rep["id"],
        "family_letter": entry["letter"],
        "family_dimension": int(entry["dim"]),
        "family_tier": family_tier(entry["letter"]),
        "representative_coordinate_symbolic": entry["representative_coordinate"],
        "sample_parameters": bridge.format_vector(bridge.sample_parameters_for_dimension(int(entry["dim"]))),
        "representative_coordinate_magnetic_sample": bridge.format_vector(sample_mag),
        "representative_coordinate_conventional_sample": bridge.format_vector(sample_conv),
        "multiplicity": int(entry["mult"]),
        "sample_orbit_size": len(orbit),
        "site_symmetry": entry["site_symmetry"],
        "stabilizer_summary": {
            "unitary_size": stabilizer["bridge_unitary_count"],
            "antiunitary_size": stabilizer["bridge_antiunitary_count"],
            "unitary_indices": stabilizer["unitary_indices"],
            "antiunitary_indices": stabilizer["antiunitary_indices"],
        },
        "local_rep": {
            "label": local_rep["label"],
            "dimension": local_rep["dimension"],
            "local_rep_scope": local_rep["local_rep_scope"],
            "definition": local_rep["definition"],
            "character_on_unitary_stabilizer": local_rep["character_on_unitary_stabilizer"],
        },
        "orbit": [
            {
                "source_operation_index": site["source_operation_index"],
                "time_reversal_source": site["time_reversal_source"],
                "magnetic_coordinate": site["magnetic_coordinate"],
                "conventional_coordinate": site["conventional_coordinate"],
            }
            for site in orbit
        ],
        "manifold_multiplicities": manifold_multiplicities,
        "manifold_band_characters": manifold_band_characters,
        "unknown_vector": unknown_vector,
        "compatibility_zero": compatibility_zero,
        "bs_basis_coefficients": coeffs,
    }


def build_expanded_candidates(ctx: dict[str, Any]) -> dict[str, Any]:
    group_tables = build_group_tables(ctx)
    manifold_globals = manifold_global_unitary_indices(ctx, group_tables)

    generators: list[dict[str, Any]] = []
    failures: list[dict[str, Any]] = []
    for letter in INCLUDED_FAMILIES:
        entry = next(item for item in ctx["wyckoff_entries"] if item["letter"] == letter)
        for local_rep in LOCAL_REP_LIBRARY[letter]:
            try:
                generators.append(induce_candidate(entry, local_rep, ctx, group_tables, manifold_globals))
            except Exception as exc:  # pragma: no cover - failure path should stay visible in JSON
                failures.append(
                    {
                        "generator_id": local_rep["id"],
                        "family_letter": letter,
                        "error": str(exc),
                    }
                )

    if failures:
        raise ValueError(f"candidate generation unexpectedly failed: {failures}")

    column_order = [generator["generator_id"] for generator in generators]
    a_expanded_columns = [generator["unknown_vector"] for generator in generators]
    coeff_columns = [generator["bs_basis_coefficients"] for generator in generators]
    a_expanded = sp.Matrix.hstack(*[sp.Matrix(column) for column in a_expanded_columns])
    coeff_matrix = sp.Matrix.hstack(*[sp.Matrix(column) for column in coeff_columns])

    return {
        "generators": generators,
        "column_order": column_order,
        "A_expanded_columns": a_expanded_columns,
        "coeff_columns": coeff_columns,
        "rank_z": int(a_expanded.rank()),
        "rank_q": int(a_expanded.rank()),
        "coeff_rank": int(coeff_matrix.rank()),
    }


def choose_integer_basis(expanded: dict[str, Any]) -> dict[str, Any]:
    coefficient_columns = [sp.Matrix(column) for column in expanded["coeff_columns"]]
    full_rank = int(sp.Matrix.hstack(*coefficient_columns).rank())

    chosen_subset: tuple[int, ...] | None = None
    relation_by_id: dict[str, list[int]] = {}
    for subset in itertools.combinations(range(len(coefficient_columns)), full_rank):
        basis_matrix = sp.Matrix.hstack(*[coefficient_columns[index] for index in subset])
        if int(basis_matrix.rank()) != full_rank:
            continue
        current_relations: dict[str, list[int]] = {}
        ok = True
        for generator_id, coeff_column in zip(expanded["column_order"], coefficient_columns):
            solution = basis_matrix.gauss_jordan_solve(coeff_column)[0]
            if any(not value.is_integer for value in solution):
                ok = False
                break
            current_relations[generator_id] = [int(value) for value in solution]
        if ok:
            chosen_subset = subset
            relation_by_id = current_relations
            break

    if chosen_subset is None:
        raise ValueError("failed to find an exact integer subset basis for the expanded candidates")

    basis_ids = [expanded["column_order"][index] for index in chosen_subset]
    basis_vectors = [expanded["A_expanded_columns"][index] for index in chosen_subset]
    basis_coefficients = [expanded["coeff_columns"][index] for index in chosen_subset]

    dependent_ids = [generator_id for generator_id in expanded["column_order"] if generator_id not in basis_ids]
    return {
        "basis_ids": basis_ids,
        "basis_vectors": basis_vectors,
        "basis_coefficients": basis_coefficients,
        "candidate_to_basis_relations": relation_by_id,
        "dependent_ids": dependent_ids,
        "rank_z": len(basis_ids),
    }


def build_bs_vs_ai_expanded_summary(expanded: dict[str, Any], basis: dict[str, Any], ctx: dict[str, Any]) -> dict[str, Any]:
    bs_rank = len(ctx["basis_raw"]["basis_vectors"])
    ai_min_summary = load_json(ROOT / "single_group_bs_vs_ai_min_summary.json")
    basis_matrix = sp.Matrix.hstack(*[sp.Matrix(column["vector"]) for column in ctx["basis_raw"]["basis_vectors"]])
    expanded_matrix = sp.Matrix.hstack(*[sp.Matrix(column) for column in expanded["A_expanded_columns"]])

    return {
        "group_number": GROUP_NUMBER,
        "rank_BS_with_planes": bs_rank,
        "rank_AI_min": int(ai_min_summary["rank_AI_min"]),
        "rank_AI_expanded": int(expanded["rank_z"]),
        "AI_expanded_in_BS": int(sp.Matrix.hstack(basis_matrix, expanded_matrix).rank()) == bs_rank,
        "rank_span_BS_plus_AI_expanded": int(sp.Matrix.hstack(basis_matrix, expanded_matrix).rank()),
        "raw_candidate_count": len(expanded["column_order"]),
        "basis_generator_ids": basis["basis_ids"],
        "new_independent_directions_vs_min_prototype": int(expanded["rank_z"]) - int(ai_min_summary["rank_AI_min"]),
        "remaining_bs_rank_gap": bs_rank - int(expanded["rank_z"]),
        "new_coverage_statement": "The expanded candidate lattice raises the atomic-side rank from 2 to 6, so it adds 4 independent directions beyond the earlier minimal prototype.",
        "remaining_gap_statement": "The remaining rank-2 gap is consistent with the still-excluded antiunitary families/coreps; this is still not the full single-group AI lattice.",
        "missing_pieces": [
            "full magnetic local coreps on a,b,d,e,g,h",
            "magnetic-corep treatment for the antiunitary parameter families n,i,j",
        ],
        "scope_note": "This remains an expanded single-group AI candidate lattice, not the final BS/AI result and not a final topological classification.",
    }


